// Regenerates src/lib/card-scene-icons.ts from the scene catalog.
// Run after editing supabase/functions/_shared/card-scenes.json:
//   node scripts/generate-card-scene-icons.mjs
import fs from 'node:fs';

const scenes = JSON.parse(fs.readFileSync('supabase/functions/_shared/card-scenes.json', 'utf8'));
const icons = [...new Set(scenes.map((s) => s.icon))].sort();

const out = `// Generated by scripts/generate-card-scene-icons.mjs — do not edit by hand.
// Each icon is imported by name so only the ones the scenes use are bundled.
import {
${icons.map((i) => `  ${i} as ${i}Icon,`).join('\n')}
  type LucideIcon,
} from 'lucide-react';

export const SCENE_ICONS: Record<string, LucideIcon> = {
${icons.map((i) => `  ${i}: ${i}Icon,`).join('\n')}
};
`;
fs.writeFileSync('src/lib/card-scene-icons.ts', out);
console.log(`Wrote ${icons.length} icons for ${scenes.length} scenes.`);
