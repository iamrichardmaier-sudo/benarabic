#!/usr/bin/env node
/**
 * Copies the conjugation engine into the Scriptable script.
 *
 * The widget cannot import from the app, so wazn-review.js carries a plain-JS
 * copy of src/lib/conjugation.ts and src/lib/verb-table.ts between the
 * "conjugation engine" markers. Run this after changing either file:
 *
 *   node scripts/scriptable/sync-conjugation.mjs
 *
 * It strips the types (TypeScript's own transpiler) and the import/export
 * lines, and replaces the block in place.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
let ts;
try {
  ts = require('typescript');
} catch {
  ts = require(process.env.TYPESCRIPT_PATH || 'typescript');
}

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const target = join(root, 'scripts', 'scriptable', 'wazn-review.js');
const BEGIN = '// ---- conjugation engine (generated by sync-conjugation.mjs from src/lib/conjugation.ts and src/lib/verb-table.ts; do not edit by hand) ----';
const END = '// ---- end of conjugation engine ----';

const strip = (file) => {
  const src = readFileSync(join(root, 'src', 'lib', file), 'utf8');
  const js = ts.transpileModule(src, {
    compilerOptions: { target: ts.ScriptTarget.ES2019, module: ts.ModuleKind.ESNext, removeComments: false },
  }).outputText;
  return js
    .split('\n')
    .filter((line) => !/^\s*import\s/.test(line) && !/^export\s*\{\s*\};?\s*$/.test(line))
    .map((line) => line.replace(/^export\s+(default\s+)?/, ''))
    .join('\n')
    .trim();
};

// Each file in its own scope: both declare FATHA, SHADDA and the like, and
// neither may collide with the script's own top-level names.
const block = [
  BEGIN,
  'const WaznConjugationCore = (() => {',
  strip('conjugation.ts'),
  'return { conjugate, PEOPLE };',
  '})();',
  '',
  'const WaznConjugation = (() => {',
  'const { conjugate, PEOPLE } = WaznConjugationCore;',
  strip('verb-table.ts'),
  'return { entryTable, buildVerbTable, whichForm, TABLE_ORDER, PRONOUN, DUAL };',
  '})();',
  END,
].join('\n');
const script = readFileSync(target, 'utf8');
const a = script.indexOf(BEGIN);
const b = script.indexOf(END);
if (a < 0 || b < 0) throw new Error('The conjugation engine markers are missing from wazn-review.js.');
writeFileSync(target, script.slice(0, a) + block + script.slice(b + END.length));
console.log('Conjugation engine copied into wazn-review.js.');
